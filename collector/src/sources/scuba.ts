// CISA's SCuBA assessment tools: ScubaGoggles (Google Workspace) and ScubaGear (Microsoft 365 and
// Entra ID). Both are CC0 and both write the same ScubaResults JSON file:
//
//   { MetaData: { Tool, ToolVersion, TenantId, TimestampZulu, ... },
//     Results: { <product>: [ { GroupName, GroupNumber, Controls: [ { "Control ID", Result, Criticality, Details } ] } ] } }
//
// Confirmed against each repository's own sample report and the code that writes it:
// ScubaGoggles scubagoggles/reporter/reporter.py (_get_test_result, _build_report_table) and
// scubagoggles/sample-report/ScubaResults_*.json; ScubaGear Modules/CreateReport/CreateReport.psm1
// (Get-TestResult), Modules/Orchestrator.psm1 (Merge-JsonOutput) and Sample-Reports/ScubaResults_*.json.
//
// The customer runs the tool in its own pipeline (ScubaGear in a Windows job) and passes the file, or
// the output folder, to the collector. One result per policy id. The tool's Details column can name
// users, groups and OUs, so it is never copied: a result carries the policy's outcome and criticality.
//
// Result values and what they become:
//   Pass                                    pass
//   Fail, Warning (a SHOULD not met)         fail
//   N/A, No events found, Omitted, Error,
//   Error - Test results missing,
//   Incorrect result, "-" (deleted)         skipped (the tool could not judge, or the customer said so)
// When one policy has several rows, the worst counts: any fail fails; a pass needs at least one pass.
//
// Retiring policies: a check whose catalogue entry carries `retiredIn` (build_scuba_catalog.py copies it from
// CISA's ScubaGear baselines/removedpolicies.md: the Defender baseline, EXO 8-17 and Teams 6-8, removed
// 2026-04 for ScubaGear 2.0.0) is version-gated on the report's MetaData.ToolVersion. ScubaGear writes that
// field in Merge-JsonOutput as "ToolVersion" = $ModuleVersion, the ScubaGear.psd1 manifest version
// (Modules/Orchestrator.psm1, line 1346 at v1.8.0, line 1910 on main at c5feaa3c, read 2026-10-20).
//   ToolVersion < retiredIn, missing or unparsable: reported exactly like any other check (v1.8.0 still
//     evaluates these policies, and their replacements exist only in the unreleased 2.0.0).
//   ToolVersion >= retiredIn: no result, not even a "did not report" skip; the run warns once, naming each
//     retired id and its replacement. A pre-release such as 2.0.0-rc1 counts as 2.0.0: it ships the new baselines.

import { readFileSync } from "node:fs";
import { basename, join } from "node:path";
import { DEFAULT_CATALOG_DIR } from "../catalog.ts";
import type { Outcome, Result, Source, SourceContext } from "../types.ts";
import { arr, isObj, str, type Obj } from "./shared-cloud.ts";
import { idList, paths, posNum, readJsonFile, resolveReport, staleness } from "./report_files.ts";

interface ScubaSpec {
  name: "scubagoggles" | "scubagear";
  /** MetaData.Tool as the tool writes it. */
  tool: string;
  suite: string;
  /** Policy id prefix, e.g. "GWS." or "MS.". */
  idPrefix: string;
  optResults: string;
  optMaxAge: string;
  howToRun: string;
}

const DEFAULT_MAX_AGE_DAYS = 30;
const RESULTS_FILE = /^ScubaResults.*\.json$/i;

interface Retiring { policy: string; retiredIn: number[]; label: string; removed: string; replacedBy: string | null }
interface Catalogue { ids: string[]; retiring: Map<string, Retiring> }

/** "1.8.0" -> [1, 8, 0]; "v2.0.0-rc1" -> [2, 0, 0]; anything without a leading number -> null. */
export function versionOf(v: string | undefined): number[] | null {
  const m = v?.trim().match(/^v?(\d+)(?:\.(\d+))?(?:\.(\d+))?/);
  return m ? [Number(m[1]), Number(m[2] ?? 0), Number(m[3] ?? 0)] : null;
}

const atLeast = (a: number[], b: number[]) => { for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] > b[i]; return true; };

/** The check ids, and those being retired, in the shipped catalogue for this source (generated by build_scuba_catalog.py). */
function readCatalogue(name: string, dir = DEFAULT_CATALOG_DIR): Catalogue {
  try {
    const doc = JSON.parse(readFileSync(join(dir, `${name}.json`), "utf8")) as { checks?: unknown };
    const checks = arr(doc.checks).filter(isObj).filter((c) => String(c.id).startsWith(`${name}.`));
    const retiring = new Map<string, Retiring>();
    for (const c of checks) {
      const v = versionOf(str(c.retiredIn));
      if (v) retiring.set(String(c.id), { policy: (str(c.title) ?? String(c.id)).split(":")[0], retiredIn: v, label: str(c.retiredIn)!, removed: str(c.removed) ?? "?", replacedBy: str(c.replacedBy) ?? null });
    }
    return { ids: checks.map((c) => String(c.id)), retiring };
  } catch {
    return { ids: [], retiring: new Map() };
  }
}

export const checkIdFor = (source: string, policyId: string) => `${source}.${policyId.trim().toLowerCase()}`;

function outcomeOf(result: string): Outcome {
  const r = result.trim().toLowerCase();
  if (r === "pass") return "pass";
  if (r === "fail" || r === "warning") return "fail";
  return "skipped";
}

/** Every control row in Results, whatever the nesting PowerShell's ConvertTo-Json gave a one-item list. */
function controlRows(results: unknown): Obj[] {
  const rows: Obj[] = [];
  if (!isObj(results)) return rows;
  for (const groups of Object.values(results)) {
    for (const g of Array.isArray(groups) ? groups : [groups]) {
      if (!isObj(g)) continue;
      const cs = g.Controls;
      for (const c of Array.isArray(cs) ? cs : [cs]) if (isObj(c)) rows.push(c);
    }
  }
  return rows;
}

function makeScuba(spec: ScubaSpec, catalogue: Catalogue = readCatalogue(spec.name)): Source {
  const emits = catalogue.ids;
  const known = new Set(emits);
  const retiring = catalogue.retiring;
  return {
    name: spec.name,
    options: {
      [spec.optResults]: { type: "string", multiple: true, help: `${spec.tool} ScubaResults*.json, or the output folder (newest file wins); ${spec.howToRun}` },
      [spec.optMaxAge]: { type: "string", help: `days a results file stays current (default ${DEFAULT_MAX_AGE_DAYS})` },
    },
    emits,
    describe(opts) {
      const ps = paths(opts[spec.optResults]);
      return `${spec.tool} results ${ps.length ? ps.map((p) => basename(p)).join(", ") : "(none given)"}`;
    },
    async run(ctx: SourceContext): Promise<Result[]> {
      const files = paths(ctx.opts[spec.optResults]);
      const maxAge = posNum(ctx.opts[spec.optMaxAge], DEFAULT_MAX_AGE_DAYS);
      const skipAll = (resource: string, why: string): Result[] => emits.map((c) => ({ check: c, resource, result: "skipped" as const, detail: why }));
      if (!files.length) return skipAll(`${spec.suite} tenant`, `give --${spec.optResults} <ScubaResults json or folder>; ${spec.howToRun}`);
      const out: Result[] = [];
      for (const given of files) {
        const p = resolveReport(given, RESULTS_FILE);
        if (typeof p !== "string") { out.push(...skipAll(`${spec.tool} ${basename(given)}`, p.error)); continue; }
        const r = readJsonFile(p);
        if ("error" in r) { out.push(...skipAll(`${spec.tool} ${basename(p)}`, r.error)); continue; }
        const doc = r.data;
        const meta = isObj(doc) && isObj(doc.MetaData) ? doc.MetaData : {};
        const tenant = str(meta.TenantId)?.trim();
        const resource = tenant ? `${spec.suite} tenant ${tenant}` : `${spec.tool} ${basename(p)}`;
        const tool = str(meta.Tool);
        if (!isObj(doc) || !isObj(doc.Results)) { out.push(...skipAll(resource, `${basename(p)} has no Results object; not a ScubaResults file`)); continue; }
        if (tool && tool.toLowerCase() !== spec.tool.toLowerCase()) { out.push(...skipAll(resource, `${basename(p)} was written by ${tool}, not ${spec.tool}`)); continue; }
        const stale = staleness(str(meta.TimestampZulu), ctx.now, maxAge, `${spec.tool} run`);
        if (stale) { out.push(...skipAll(resource, stale)); continue; }
        const version = str(meta.ToolVersion) ?? "version unknown";
        const ver = versionOf(str(meta.ToolVersion));
        // Checks this report's ScubaGear no longer has: none when the version is missing or older.
        const retired = new Map([...retiring].filter(([, r]) => ver !== null && atLeast(ver, r.retiredIn)));
        const when = str(meta.TimestampZulu)!.slice(0, 10);

        // Worst outcome per policy id; the raw result strings are kept for the detail.
        const per = new Map<string, { outcome: Outcome; results: string[]; criticality: string }>();
        for (const row of controlRows(doc.Results)) {
          const id = str(row["Control ID"])?.trim();
          if (!id || !id.toUpperCase().startsWith(spec.idPrefix)) continue;
          const raw = str(row.Result) ?? "(no result)";
          const o = outcomeOf(raw);
          const prev = per.get(id);
          const worst: Outcome = !prev ? o : prev.outcome === "fail" || o === "fail" ? "fail" : prev.outcome === "pass" || o === "pass" ? "pass" : "skipped";
          per.set(id, { outcome: worst, results: [...(prev?.results ?? []), raw.slice(0, 40)], criticality: (str(row.Criticality) ?? prev?.criticality ?? "-").slice(0, 40) });
        }
        if (!per.size) { out.push(...skipAll(resource, `${basename(p)} lists no ${spec.idPrefix}* policy results`)); continue; }

        const unmapped: string[] = [];
        const seen = new Set<string>();
        for (const [id, v] of per) {
          const check = checkIdFor(spec.name, id);
          if (retired.has(check)) continue;
          if (!known.has(check)) { unmapped.push(id); continue; }
          seen.add(check);
          const what = [...new Set(v.results)].join(" / ");
          const meaning = v.outcome === "pass" ? "met" : v.outcome === "fail" ? (/warning/i.test(what) && !/fail/i.test(what) ? "a SHOULD not met" : "not met") : "not judged by the tool";
          out.push({ check, resource, result: v.outcome,
            detail: `${spec.tool} ${version} on ${when}: ${id} result ${what} (criticality ${v.criticality}); ${meaning}` });
        }
        // Policies in the pinned mapping that this run did not assess (a product left out, or renamed).
        for (const c of emits) if (!seen.has(c) && !retired.has(c)) out.push({ check: c, resource, result: "skipped", detail: `${spec.tool} ${version} on ${when} did not report this policy (product not assessed, or the policy id changed)` });
        if (retired.size) {
          const gone = [...retired.values()].map((r) => `${r.policy} (removed ${r.removed}, now ${r.replacedBy ?? "no replacement"})`);
          ctx.warn(`${spec.name}: ${spec.tool} ${version} (${basename(p)}) is ${[...retired.values()][0].label} or later, so ${retired.size} policies CISA retired get no result${idList(gone, "", gone.length)}`);
        }
        if (unmapped.length) ctx.warn(`${spec.name}: ${unmapped.length} policy id(s) in ${basename(p)} are not in the pinned catalogue and were left out${idList(unmapped)}`);
      }
      return out;
    },
  };
}

export const scubagoggles = makeScuba({
  name: "scubagoggles", tool: "ScubaGoggles", suite: "gws", idPrefix: "GWS.",
  optResults: "scubagoggles-results", optMaxAge: "scubagoggles-max-age-days",
  howToRun: "run `scubagoggles gws -o <dir>` first",
});

export const scubagear = makeScuba({
  name: "scubagear", tool: "ScubaGear", suite: "m365", idPrefix: "MS.",
  optResults: "scubagear-results", optMaxAge: "scubagear-max-age-days",
  howToRun: "run `Invoke-SCuBA -ProductNames * -OutPath <dir>` in a Windows job first",
});
